// Generates contracts/script/ByteGateBitmap.sol -- the ONE code bitmap the
// byte-gate deploy mints with.
//
// WHY A NEW FILE RATHER THAN SpikeBitmaps.sol. That library holds 37x37 grids
// of 172 bytes, which is QR version 5. The spike token's CODE_BYTES is 407
// since version 10, so every one of its bitmaps is now the wrong length and
// `mint` would revert with BadCodeLength. Regenerating all 27 of them to test
// ONE token would cost twenty-seven robustness solves for no gain.
//
// The domain is the REAL one. A bitmap encodes its own url, and byte counts and
// run structure vary per bitmap, so solving against a placeholder would measure
// a token nobody can mint. This is testnet and no mainnet re-solve rule is being
// dodged: it is the same generator the renderer tests and the live mint use.
//
// ONE TOKEN, ONE PROCESS. Solving renders and decodes the candidate in eight
// states at ten raster sizes, and resvg's buffers are NATIVE -- outside the JS
// heap, so --max-old-space-size does not bound them. A 27-token run once reached
// 2.0 GB. One token is well within the cap, but run it through safe-build.sh
// anyway.
//
//   ~/scripts/safe-build.sh node tools/byte-gate-bitmap.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { tokenBitmap, BYTES } from "./token-bitmap.mjs";
import { payloadFor } from "./qart.mjs";

const DOMAIN = "machinereadableonly.com";
const TOKEN_ID = 1;

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "contracts", "script", "ByteGateBitmap.sol");

const solved = tokenBitmap(DOMAIN, TOKEN_ID);
const hex = solved.hex ?? solved;
if (typeof hex !== "string" || hex.length !== BYTES * 2) {
  console.error(`expected ${BYTES * 2} hex characters, got ${hex?.length}`);
  process.exit(1);
}

// Split so no source line runs past the project's width, the same way
// SpikeBitmaps and MroTestBase already write their literals.
const chunks = hex.match(/.{1,180}/g).map(c => `        hex"${c}"`).join("\n");

writeFileSync(out, `// SPDX-License-Identifier: MIT
// GENERATED by tools/byte-gate-bitmap.mjs -- do not edit by hand.
// Regenerate with: ~/scripts/safe-build.sh node tools/byte-gate-bitmap.mjs
pragma solidity ^0.8.30;

/// @notice The one code bitmap the byte-gate deploy mints with.
/// @dev Token ${TOKEN_ID} on ${DOMAIN}, ${BYTES} bytes, QR version 10.
/// Payload: ${payloadFor(DOMAIN, TOKEN_ID)}
///
/// A token's code encodes its own url, so this cannot be shared with another
/// id and cannot be invented. It comes from the same generator the renderer
/// tests and the live mint use.
library ByteGateBitmap {
    uint256 internal constant BYTES_LEN = ${BYTES};

    function code() internal pure returns (bytes memory) {
        return
${chunks};
    }
}
`);

console.log(`wrote ${out}`);
console.log(`  ${BYTES} bytes, token ${TOKEN_ID} on ${DOMAIN}`);
