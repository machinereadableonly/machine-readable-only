// The day frame: 376 cells in the two rings immediately outside the code block,
// ordered so the ring opens at the top and closes at the bottom as days accrue.
//
// Coordinates are local to a 49 x 49 grid (the 45-cell block plus two rings), so
// they do not change when completed-year rings widen the canvas. The renderer
// adds the canvas offset.
import { writeFileSync, mkdirSync } from "node:fs";

export const BLOCK = 45;              // 37 code modules + a 4-cell quiet zone each side
export const THICK = 2;               // frame rings
export const LOCAL = BLOCK + 2 * THICK;   // 49
export const DAY_CELLS = 365;
export const TOTAL_CELLS = LOCAL * LOCAL - BLOCK * BLOCK;   // 376

// 365 is odd and two concentric rings always hold an even count, so an exact fit
// is impossible. The surplus 11 cells sit at the bottom, where the ring stays
// visibly open all year and seals only once the heart is whole.
export function frameCells() {
  const cells = [];
  const mid = (LOCAL - 1) / 2;
  for (let y = 0; y < LOCAL; y++) {
    for (let x = 0; x < LOCAL; x++) {
      const ring = Math.min(x, y, LOCAL - 1 - x, LOCAL - 1 - y);
      if (ring >= THICK) continue;                 // inside the block
      const angle = Math.atan2(x - mid, -(y - mid)); // 0 straight up, sign splits the arms
      cells.push({ x, y, key: Math.abs(angle), ring, side: Math.sign(angle) || 1 });
    }
  }
  cells.sort((a, b) => a.key - b.key || a.ring - b.ring || a.side - b.side);
  return cells.map(c => [c.x, c.y]);
}

// The same 376 cells as a bitmap, one 8-byte big-endian value per local row,
// bit LOCAL-1-x set when the cell at x is part of the frame.
//
// This exists purely for gas. A whole frame lights every cell, and a renderer
// that has this constant can OR 49 rows straight in instead of walking all 376
// cells to discover the same thing -- and walking them measured 1,131 gas each.
// The ghost is then the frame minus what is lit, which is one XOR per row.
export function frameRows(cells) {
  const rows = new Array(LOCAL).fill(0n);
  for (const [x, y] of cells) rows[y] |= 1n << BigInt(LOCAL - 1 - x);
  return rows;
}

export function toSolidity(cells) {
  const hex = cells.map(([x, y]) =>
    x.toString(16).padStart(2, "0") + y.toString(16).padStart(2, "0")).join("");
  const rowsHex = frameRows(cells).map(r => r.toString(16).padStart(16, "0")).join("");
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.30;

// GENERATED by tools/frame-geometry.mjs -- do not edit by hand.
// ${cells.length} frame cells in fill order on a ${LOCAL}x${LOCAL} local grid, being the
// two rings just outside the ${BLOCK}-cell code block. One cell per credited day;
// the last ${cells.length - DAY_CELLS} light only once the heart is whole.
library FrameGeometry {
    uint256 constant BLOCK = ${BLOCK};
    uint256 constant THICK = ${THICK};
    uint256 constant LOCAL = ${LOCAL};
    uint256 constant DAY_CELLS = ${DAY_CELLS};
    uint256 constant CELL_COUNT = ${cells.length};

    // Two bytes per cell: x then y, local coordinates.
    function cells() internal pure returns (bytes memory) {
        return hex"${hex}";
    }

    // The same cells as a bitmap: eight bytes per local row, bit LOCAL-1-x set
    // when x is a frame cell. Lets a renderer light a whole frame without
    // walking every cell to work out which they are.
    function rows() internal pure returns (bytes memory) {
        return hex"${rowsHex}";
    }
}
`;
}

if (process.argv[1] && process.argv[1].endsWith("frame-geometry.mjs")) {
  const cells = frameCells();
  mkdirSync("../contracts/src/render", { recursive: true });
  writeFileSync("../contracts/src/render/FrameGeometry.sol", toSolidity(cells));
  mkdirSync("out", { recursive: true });
  writeFileSync("out/frame.json", JSON.stringify(cells));
  console.log(`wrote FrameGeometry.sol with ${cells.length} cells (${DAY_CELLS} days + ${cells.length - DAY_CELLS} sealing)`);
}
